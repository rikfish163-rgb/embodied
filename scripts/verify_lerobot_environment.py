def main(argv: list[str] | None = None) -> int:
    arguments = _argument_parser().parse_args(argv)
    try:
        if arguments.command == "audit-lock":
            payload = audit_dependency_lock(
                requirements=arguments.requirements,
                lock=arguments.lock,
                output=arguments.output,
            )
            return 3 if payload["status"] == "blocked" else 0
        if arguments.command == "blocked-receipt-draft":
            build_dependency_blocked_receipt(
                repository=arguments.repository,
                expected_prefix=arguments.expected_prefix,
                dependency_evidence=arguments.dependency_evidence,
                supporting_evidence=arguments.supporting_evidence,
                data_free_kib=arguments.data_free_kib,
                root_free_kib=arguments.root_free_kib,
                output=arguments.output,
            )
            return 0
        if arguments.command == "preflight-blocked-receipt-draft":
            build_preflight_blocked_receipt(
                repository=arguments.repository,
                expected_prefix=arguments.expected_prefix,
                failure_stage=arguments.failure_stage,
                reason_code=arguments.reason_code,
                data_free_kib=arguments.data_free_kib,
                root_free_kib=arguments.root_free_kib,
                supporting_evidence=arguments.supporting_evidence,
                output=arguments.output,
            )
            return 0
    except (ContractError, OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"LeRobot environment verification failed closed: {exc}", file=sys.stderr)
        return 2
    raise AssertionError(f"unhandled command: {arguments.command}")


if __name__ == "__main__":
    raise SystemExit(main())
