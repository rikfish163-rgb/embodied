def make_synthetic_batch(torch_module, *, batch_size: int, device: str):
    """Create the fixed synthetic batch without reading M2 or any training artifact."""

    if batch_size < 1:
        raise ContractError("synthetic batch size must be positive")
    generator = torch_module.Generator(device="cpu")
    generator.manual_seed(0)
    tensors = {
        "observation.images.front": torch_module.rand(
            batch_size, 3, 128, 128, generator=generator, dtype=torch_module.float32
        ),
        "observation.images.wrist": torch_module.rand(
            batch_size, 3, 128, 128, generator=generator, dtype=torch_module.float32
        ),
        "observation.state": torch_module.rand(
            batch_size, 8, generator=generator, dtype=torch_module.float32
        ),
        "action": torch_module.rand(
            batch_size, 16, 8, generator=generator, dtype=torch_module.float32
        ),
        "action_is_pad": torch_module.zeros(
            batch_size, 16, dtype=torch_module.bool
        ),
    }
    return {key: value.to(device) for key, value in tensors.items()}


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _evidence_entries(repository: Path, paths: list[Path]) -> list[dict[str, object]]:
    """Describe regular evidence files without allowing paths outside the repo."""

    root = repository.resolve()
    entries = []
    for path in paths:
        resolved = path.resolve()
        try:
            relative = resolved.relative_to(root).as_posix()
        except ValueError as exc:
            raise ContractError("supporting evidence is outside the repository") from exc
        if path.is_symlink() or not resolved.is_file():
            raise ContractError(f"supporting evidence is not a regular file: {relative}")
        entries.append(
            {
                "path": relative,
                "sha256": sha256_file(resolved),
                "size_bytes": resolved.stat().st_size,
            }
        )
    entries.sort(key=lambda item: str(item["path"]))
    return entries


def verify_runtime_identity(
    *,
    repository: Path,
    expected_prefix: Path,
    executable: Path,
    sys_prefix: Path,
    python_version: tuple[int, int, int],
    environment: Mapping[str, str],
    module_paths: Mapping[str, Path],
) -> dict[str, object]:
    """Prove that Python and every adoption dependency come from one prefix."""

    root = repository.resolve()
    prefix = expected_prefix.resolve()
    expected_executable = (prefix / "bin" / "python").resolve()
    actual_executable = executable.resolve()
    if actual_executable != expected_executable:
        raise ContractError("runtime executable is outside the unique LeRobot prefix")
    if sys_prefix.resolve() != prefix:
        raise ContractError("runtime sys.prefix is not the unique LeRobot prefix")
    if python_version[:2] != (3, 12):
        raise ContractError("LeRobot launcher requires Python 3.12")
    if "VIRTUAL_ENV" in environment:
        raise ContractError("VIRTUAL_ENV must be unset for the LeRobot isolate")
    if environment.get("PYTHONPATH") != str(root / "src"):
        raise ContractError("PYTHONPATH must contain only the repository src directory")
    expected_path = f"{prefix}/bin:/usr/local/bin:/usr/bin:/bin"
    if environment.get("PATH") != expected_path:
        raise ContractError("PATH does not select the unique LeRobot prefix")
    for name, module_path in sorted(module_paths.items()):
        try:
            module_path.resolve().relative_to(prefix)
        except ValueError as exc:
            raise ContractError(f"{name} module path is outside the LeRobot prefix") from exc

    return {
        "python_version": ".".join(str(part) for part in python_version),
        "prefix": str(prefix),
        "executable": str(actual_executable),
        "executable_sha256": "sha256:" + sha256_file(actual_executable),
        "module_paths": {
            name: str(module_path.resolve()) for name, module_path in sorted(module_paths.items())
        },
    }


def exercise_policy(
    torch_module,
    *,
    policy,
    optimizer,
    batch: Mapping[str, object],
    device: str,
    accumulation_steps: int,
) -> dict[str, object]:
    """Run the complete train and direct chunk-prediction adoption chain."""

    if accumulation_steps < 1:
        raise ContractError("gradient accumulation steps must be positive")

    def autocast_context():
        if device == "cuda":
            return torch_module.autocast(device_type="cuda", dtype=torch_module.bfloat16)
        return contextlib.nullcontext()

    policy.train()
    optimizer.zero_grad(set_to_none=True)
    observed_loss = None
    observed_loss_dict = None
    for _ in range(accumulation_steps):
        with autocast_context():
            loss, loss_dict = policy.forward(batch)
        if loss.ndim != 0 or not bool(torch_module.isfinite(loss).item()):
            raise CompatibilityFailure("non_finite", "ACT loss is not a finite scalar")
        loss_values = [
            float(value.detach().cpu()) if hasattr(value, "detach") else float(value)
            for value in loss_dict.values()
        ]
        if not all(math.isfinite(value) for value in loss_values):
            raise CompatibilityFailure("non_finite", "ACT loss_dict contains non-finite values")
        (loss / accumulation_steps).backward()
        observed_loss = float(loss.detach().cpu())
        observed_loss_dict = dict(zip(loss_dict, loss_values, strict=True))

    gradients = [parameter.grad for parameter in policy.parameters() if parameter.grad is not None]
    if not gradients or not all(
        bool(torch_module.isfinite(gradient).all().item()) for gradient in gradients
    ):
        raise CompatibilityFailure("non_finite", "ACT gradients are missing or non-finite")
    optimizer.step()

    policy.eval()
    with torch_module.no_grad(), autocast_context():
        prediction = policy.predict_action_chunk(batch)
    expected_shape = (batch["observation.state"].shape[0], 16, 8)
    if tuple(prediction.shape) != expected_shape:
        raise CompatibilityFailure(
            "act_api_incompatible",
            f"ACT prediction shape {tuple(prediction.shape)} != {expected_shape}",
        )
    if not bool(torch_module.isfinite(prediction).all().item()):
        raise CompatibilityFailure("non_finite", "ACT prediction contains non-finite values")

    return {
        "loss": observed_loss,
        "loss_dict": observed_loss_dict,
        "loss_finite": True,
        "loss_dict_finite": True,
        "gradients_finite": True,
        "optimizer_step_completed": True,
        "prediction_shape": list(prediction.shape),
        "prediction_finite": True,
    }


def audit_dependency_lock(
    *, requirements: Path, lock: Path, output: Path
) -> dict[str, object]:
    """Publish non-terminal evidence explaining why this isolate is disabled."""

    read_requirement_anchors(requirements)
    lock_summary = validate_compiled_lock(lock)
    decision = known_dependency_security_gate(lock)
    payload = {
        "schema_version": "lerobot-dependency-security-evidence.v1",
        "status": decision["status"],
        "passed": decision["passed"],
        "reason_code": decision.get("reason_code"),
        "lock_classification": "development-blocked",
        "environment_creation_allowed": decision["environment_creation_allowed"],
        "smoke_allowed": decision["smoke_allowed"],
        "issues": decision["issues"],
        "lerobot_commit": LEROBOT_COMMIT,
        "requirements_sha256": sha256_file(requirements),
        "lock_sha256": sha256_file(lock),
        "package_count": lock_summary["package_count"],
        "key_requirements": lock_summary["key_requirements"],
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("x", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2, allow_nan=False)
        handle.write("\n")
    return payload


