def resource_blocker(
    phase: str,
    data_free_kib: int,
    root_free_kib: int,
) -> str | None:
    """Return the frozen disk-space blocker for a bootstrap phase, if any."""

    valid_phases = {"initial", "post-create", "post-sync", "post-smoke"}
    if phase not in valid_phases:
        raise ContractError(f"unknown resource phase: {phase}")
    data_minimum_gib = 20 if phase == "initial" else 15
    if data_free_kib < data_minimum_gib * 1024**2:
        return "insufficient_data_space"
    if root_free_kib < 3 * 1024**2:
        return "insufficient_root_space"
    return None


def validate_compiled_lock(path: Path) -> dict[str, object]:
    """Validate the resolver-produced, hash-locked cu128 requirements file."""

    text = path.read_text(encoding="utf-8")
    if "# This file was autogenerated by uv" not in text:
        raise ContractError("LeRobot lock must be generated by uv pip compile")
    if "--index-url https://pypi.org/simple" not in text:
        raise ContractError("LeRobot lock must record the public package index")

    start_pattern = re.compile(
        r"^(?P<name>[A-Za-z0-9][A-Za-z0-9_.-]*)(?:==(?P<version>[^ ;\\]+)| @ (?P<url>\S+))",
        re.MULTILINE,
    )
    starts = list(start_pattern.finditer(text))
    if not starts:
        raise ContractError("LeRobot lock contains no resolved packages")

    packages: dict[str, dict[str, object]] = {}
    for index, match in enumerate(starts):
        name = match.group("name").lower().replace("_", "-")
        if name in packages:
            raise ContractError(f"duplicate locked package: {name}")
        block_end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
        block = text[match.start() : block_end]
        version = match.group("version")
        url = match.group("url")
        hashes = re.findall(r"--hash=sha256:([0-9a-f]{64})(?:\s|$)", block)
        if version is not None and not hashes:
            raise ContractError(f"locked registry package has no SHA-256 hash: {name}")
        if version is None and not url:
            raise ContractError(f"unversioned locked package: {name}")
        packages[name] = {
            "version": version,
            "url": url,
            "hashes": hashes,
            "block": block,
        }

    lerobot = packages.get("lerobot")
    expected_lerobot_url = (
        "git+https://github.com/huggingface/lerobot.git@" + LEROBOT_COMMIT
    )
    if lerobot is None or lerobot["url"] != expected_lerobot_url:
        raise ContractError("LeRobot lock does not pin the approved upstream commit")

    key_versions = {
        "h5py": "3.16.0",
        "imageio": "2.37.4",
        "mujoco": "3.11.0",
        "numpy": "2.2.6",
        "safetensors": "0.8.0",
        "torch": "2.11.0+cu128",
        "torchvision": "0.26.0+cu128",
    }
    for name, expected_version in key_versions.items():
        if packages.get(name, {}).get("version") != expected_version:
            raise ContractError(f"wrong locked version for {name}")
    cu128_source = "# from https://download.pytorch.org/whl/cu128"
    for name in ("torch", "torchvision"):
        if cu128_source not in str(packages[name]["block"]):
            raise ContractError(f"{name} is not locked to the official cu128 index")

    return {
        "package_count": len(packages),
        "key_requirements": key_versions,
        "lerobot_commit": LEROBOT_COMMIT,
        "all_registry_requirements_hashed": all(
            package["hashes"]
            for package in packages.values()
            if package["version"] is not None
        ),
    }


def known_dependency_security_gate(path: Path) -> dict[str, object]:
    """Block environment creation for vulnerabilities confirmed by OSV evidence."""

    validate_compiled_lock(path)
    text = path.read_text(encoding="utf-8")
    versions = {
        name: match.group(1)
        for name in ("datasets", "setuptools", "torch")
        if (
            match := re.search(
                rf"^{re.escape(name)}==([^ ;\\]+)", text, flags=re.MULTILINE
            )
        )
    }
    policies = (
        ("datasets", "5.0.1", ["PYSEC-2026-3716"]),
        (
            "setuptools",
            "83.0.0",
            ["GHSA-h35f-9h28-mq5c", "PYSEC-2026-3447"],
        ),
        ("torch", "2.13.0", ["GHSA-rrmf-rvhw-rf47"]),
    )

    def release_tuple(version: str) -> tuple[int, int, int]:
        numeric = version.split("+", 1)[0]
        parts = numeric.split(".")
        if len(parts) < 3 or not all(part.isdigit() for part in parts[:3]):
            raise ContractError(f"unsupported locked version for security gate: {version}")
        return tuple(int(part) for part in parts[:3])  # type: ignore[return-value]

    issues = []
    for package, safe_floor, advisories in policies:
        installed = versions.get(package)
        if installed is None:
            raise ContractError(f"security-gated package missing from lock: {package}")
        if release_tuple(installed) < release_tuple(safe_floor):
            issues.append(
                {
                    "package": package,
                    "installed": installed,
                    "safe_floor": safe_floor,
                    "advisories": advisories,
                }
            )
    if issues:
        return {
            "status": "blocked",
            "passed": None,
            "reason_code": "dependency_security",
            "issues": issues,
            "environment_creation_allowed": False,
            "smoke_allowed": False,
        }
    return {
        "status": "passed",
        "passed": True,
        "issues": [],
        "environment_creation_allowed": True,
        "smoke_allowed": True,
    }


def _validate_source_manifest_shape(manifest: Mapping[str, object]) -> None:
    required_fields = {
        "schema_version",
        "manifest_id",
        "git_commit",
        "head_tree",
        "scope_config_sha256",
        "path_set_sha256",
        "index_entries_sha256",
        "content_entries_sha256",
        "tracked_status_sha256",
        "source_provenance_clean",
        "entries",
    }
    missing = required_fields.difference(manifest)
    if missing:
        raise ContractError(
            "source manifest is missing required fields: " + ", ".join(sorted(missing))
        )
    if manifest["schema_version"] != "lerobot-source-input-manifest.v1":
        raise ContractError("unsupported source manifest schema")
    if not re.fullmatch(r"sha256:[0-9a-f]{64}", str(manifest["manifest_id"])):
        raise ContractError("invalid source manifest identity")
    if not re.fullmatch(r"[0-9a-f]{40,64}", str(manifest["git_commit"])):
        raise ContractError("invalid source commit")
    if not isinstance(manifest["source_provenance_clean"], bool):
        raise ContractError("source_provenance_clean must be boolean")
    entries = manifest["entries"]
    if not isinstance(entries, list) or not entries:
        raise ContractError("source manifest entries must be a nonempty list")
    paths = [entry.get("path") for entry in entries if isinstance(entry, dict)]
    if len(paths) != len(entries) or paths != sorted(set(paths)):
        raise ContractError("source manifest entries must have sorted unique paths")


def source_lineage_gate(
    start_manifest: Mapping[str, object],
    current_manifest: Mapping[str, object],
) -> dict[str, object]:
    """Require exact start/current source lineage before a terminal receipt."""

    _validate_source_manifest_shape(start_manifest)
    _validate_source_manifest_shape(current_manifest)
    if start_manifest != current_manifest:
        return {
            "formal_ready": False,
            "non_acceptance": True,
            "blocker": "source_input_manifest_drift",
        }
    if start_manifest["source_provenance_clean"] is not True:
        return {
            "formal_ready": False,
            "non_acceptance": True,
            "blocker": "source_provenance_not_clean",
        }
    return {
        "formal_ready": True,
        "non_acceptance": False,
        "source_input_manifest_id": start_manifest["manifest_id"],
        "source_commit": start_manifest["git_commit"],
    }


def terminal_decision(
    *,
    requested_status: str,
    failure_class: str | None,
    evidence_complete: bool,
    resource_blocker_code: str | None,
    source_lineage: Mapping[str, object],
) -> dict[str, object]:
    """Apply fail-closed admission rules to a smoke runner's requested state."""

    if resource_blocker_code is not None:
        return {
            "status": "blocked",
            "passed": None,
            "reason_code": resource_blocker_code,
            "non_acceptance": True,
        }
    if not evidence_complete:
        return {
            "status": "blocked",
            "passed": None,
            "reason_code": "incomplete_evidence",
            "non_acceptance": True,
        }
    if source_lineage.get("formal_ready") is not True:
        return {
            "status": "blocked",
            "passed": None,
            "reason_code": str(source_lineage.get("blocker", "source_lineage_invalid")),
            "non_acceptance": True,
        }
    if requested_status == "passed":
        return {
            "status": "passed",
            "passed": True,
            "non_acceptance": False,
        }
    if (
        requested_status == "failed"
        and failure_class in COMPATIBILITY_FAILURE_ALLOWLIST
    ):
        return {
            "status": "failed",
            "passed": False,
            "failure_class": failure_class,
            "non_acceptance": False,
        }
    return {
        "status": "blocked",
        "passed": None,
        "reason_code": "unknown_failure",
        "non_acceptance": True,
    }


