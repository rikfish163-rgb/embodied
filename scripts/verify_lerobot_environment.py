def reconcile_cuda_attempts(
    attempts: list[dict[str, object]],
) -> dict[str, object]:
    """Validate the immutable 4→2→1 ladder and decide its next state."""

    expected_batches = [batch for batch, _ in CUDA_LADDER]
    observed_batches = [attempt.get("microbatch") for attempt in attempts]
    if observed_batches != expected_batches[: len(observed_batches)]:
        raise ContractError("CUDA attempts must follow the exact 4, 2, 1 ladder")
    if len(attempts) > len(CUDA_LADDER):
        raise ContractError("CUDA attempts must follow the exact 4, 2, 1 ladder")

    for index, attempt in enumerate(attempts):
        if attempt.get("evidence_complete") is not True:
            return {
                "status": "blocked",
                "passed": None,
                "failure_class": "incomplete_evidence",
            }
        result = attempt.get("result")
        if result == "passed":
            batch, accumulation = CUDA_LADDER[index]
            return {
                "status": "passed",
                "passed": True,
                "selected_microbatch": batch,
                "gradient_accumulation_steps": accumulation,
                "effective_batch": 4,
            }
        if result == "compatibility_failed":
            failure_class = attempt.get("failure_class")
            if failure_class not in COMPATIBILITY_FAILURE_ALLOWLIST:
                return {
                    "status": "blocked",
                    "passed": None,
                    "failure_class": "unknown_failure",
                }
            return {
                "status": "failed",
                "passed": False,
                "failure_class": failure_class,
            }
        if result != "oom":
            return {
                "status": "blocked",
                "passed": None,
                "failure_class": "unknown_failure",
            }

    if len(attempts) == len(CUDA_LADDER):
        return {
            "status": "failed",
            "passed": False,
            "failure_class": "cuda_oom_batch1",
        }
    next_batch, next_accumulation = CUDA_LADDER[len(attempts)]
    return {
        "status": "continue",
        "passed": None,
        "next_microbatch": next_batch,
        "next_accumulation_steps": next_accumulation,
    }


