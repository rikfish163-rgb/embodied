class ContractError(RuntimeError):
    """Raised when an immutable adoption input violates the frozen contract."""


class CompatibilityFailure(RuntimeError):
    """A deterministic, allowlisted incompatibility with complete evidence."""

    def __init__(self, failure_class: str, message: str) -> None:
        super().__init__(message)
        self.failure_class = failure_class


def read_requirement_anchors(path: Path) -> tuple[str, ...]:
    """Return the exact package anchors and reject launcher requirements."""

    lines = tuple(
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    )
    if lines != REQUIRED_ANCHORS:
        raise ContractError(
            "requirements.lerobot-act.in must contain only the frozen package anchors"
        )
    return lines


